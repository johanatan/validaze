(ns validaze.event-gen
  "test.check generators of events that a given validator accepts.

  Types come from the validator's own introspection (`:event->schema`).
  Base types, the built-in refinements and set refinements get generators
  automatically. Supply generators for predicate refinements, since a
  predicate can't be inverted."
  (:require [clojure.test.check.generators :as gen]))

(def ^:private iso-datetime
  (gen/fmap #(.format (.withZone (java.time.format.DateTimeFormatter/ofPattern "yyyy-MM-dd'T'HH:mm:ss.SSSXXX")
                                 java.time.ZoneOffset/UTC)
                      (java.time.Instant/ofEpochMilli %))
            (gen/choose 0 4102444800000)))

(def base-gens
  {:string              gen/string-alphanumeric
   :number              (gen/double* {:infinite? false :NaN? false})
   :integer             gen/large-integer
   :boolean             gen/boolean
   :object              (gen/map gen/string-alphanumeric gen/string-alphanumeric {:max-elements 3})
   :nonnegative-integer gen/nat
   :positive-integer    (gen/fmap inc gen/nat)
   :datetime            iso-datetime})

(defn- set-refinement-gens
  "Set refinements are stored as [:string [pred msg-fn]], with the set as
  the predicate's :set metadata."
  [refinements]
  (into {} (for [[k [_ [pred _]]] refinements
                 :let [members (:set (meta pred))]
                 :when members]
             [k (gen/elements (sort members))])))

(defn type-gen [gens type]
  (cond
    (keyword? type) (or (gens type)
                        (throw (ex-info (str "No generator for refinement " type) {:type type})))
    (= :enum (first type)) (gen/elements (rest type))
    (= :list (first type)) (gen/vector (type-gen gens (second type)) 0 4)
    (= :object (first type)) (gen/map (type-gen gens (nth type 1)) (type-gen gens (nth type 2))
                                      {:max-elements 3})))

(defn- map-gen
  "A generator of maps with m's keys, each value generated by (f (m k))."
  [f m]
  (let [ks (vec (keys m))]
    (gen/fmap #(zipmap ks %) (apply gen/tuple (map (comp f m) ks)))))

(defn condition-holds?
  "Whether a `[:when other-prop values]` requirement applies to props."
  [[_ other-prop values] props]
  (if (= values :exists)
    (contains? props other-prop)
    (contains? values (get props other-prop))))

(defn- satisfy-conditionals
  "Adds every conditionally required key whose condition holds, until no more apply."
  [props attrs values]
  (let [conditional (filter (comp vector? :required? val) attrs)]
    (loop [props props]
      (let [missing (for [[k {req :required?}] conditional
                          :when (and (not (contains? props k)) (condition-holds? req props))]
                      k)]
        (if (empty? missing)
          props
          (recur (merge props (select-keys values missing))))))))

(defn schema-for
  "The validator's view of the event's type, version and super-properties version."
  [validator {:strs [event_type event_version super_properties_version]}]
  ((:event->schema (meta validator)) super_properties_version event_type event_version))

(defn event-gen
  "Generates events `validator` accepts. `refinement-gens` maps refinement
  keywords to generators of values that satisfy them."
  ([validator] (event-gen validator {}))
  ([validator refinement-gens]
   (let [{:keys [events-schema super-properties-schema refinements]} (meta validator)
         gens (merge base-gens (set-refinement-gens refinements) refinement-gens)]
     (gen/let [event-type (gen/elements (sort (keys events-schema)))
               version (gen/elements (sort (keys (events-schema event-type))))
               super-version (gen/elements (or (seq (sort (keys super-properties-schema))) [nil]))
               explicit-super? gen/boolean]
       (let [event (cond-> {"event_type" event-type "event_version" version}
                     (and super-version (or explicit-super? (not= 1 super-version)))
                     (assoc "super_properties_version" super-version))
             {event-keys :keys super-keys :super-keys types :types} (schema-for validator event)
             all-keys (merge event-keys super-keys)]
         ;; A generator returned from a gen/let body is flattened.
         (gen/let [values (map-gen (fn [t] (type-gen gens t)) types)
                   include? (map-gen (constantly gen/boolean) all-keys)]
           (let [initial (into {} (for [[k {req :required?}] all-keys
                                        :when (or (true? req) (include? k))]
                                    [k (values k)]))]
             (assoc event "properties" (satisfy-conditionals initial all-keys values)))))))))

(defn base-kind
  "The JSON kind a property's type ultimately requires."
  [refinements type]
  (cond
    (vector? type) ({:enum :string :list :list :object :object} (first type))
    :else (loop [k type]
            (let [[parent _] (refinements k)]
              (if (nil? parent) k (recur parent))))))

(def ^:private sample-of-kind
  {:string "a string" :integer 7 :number 2.5 :boolean true :object {"k" "v"} :list ["x"]})

(defn wrong-kind-values
  "Values of a different JSON kind than `kind`. Integers count as numbers."
  [kind]
  (vals (apply dissoc sample-of-kind kind (when (= kind :number) [:integer]))))
